const headStrengths = ['Leadership', 'Systems thinking', 'Accountability'];
const leadStrengths = ['Team coordination', 'Quality ownership', 'Clear escalation'];
const specialistStrengths = ['Attention to detail', 'Collaboration', 'Reliable execution'];

export const workforce: Role[] = [];
let count = 0;
for (const div of divisions) {
  const add = (def: RoleDef, level: Level, manager: Role | null): Role => {
    const role: Role = {
      id: `RF-${String(++count).padStart(3, '0')}`,
      name: def.name, title: def.title, division: div.key, level,
      manager: manager?.name ?? null, managerId: manager?.id ?? null,
      mission: def.mission,
      strengths: level === 'head' ? headStrengths : level === 'lead' ? leadStrengths : specialistStrengths,
      skills: def.skills, tasks: def.tasks, color: div.color,
    };
    workforce.push(role);
    return role;
  };
  const head = add(div.head, 'head', null);
  for (const lead of div.leads) {
    const leadRole = add(lead, 'lead', head);
    for (const spec of lead.team) add(spec, 'specialist', leadRole);
  }
}

export const divisionNames = divisions.map((d) => d.key);
export const divisionLabels: Record<string, string> = Object.fromEntries(divisions.map((d) => [d.key, d.label]));
export const divisionColors: Record<string, string> = Object.fromEntries(divisions.map((d) => [d.key, d.color]));
export const rolesByDivision = (division: string) => workforce.filter((x) => x.division === division);
export const roleById = (id: string) => workforce.find((x) => x.id === id);
export const directReports = (id: string) => workforce.filter((x) => x.managerId === id);
export const isVeraRole = (id: string) => /^RF-0(6[1-9]|7[0-5])$/.test(id);
